// Regenerates components/icons/icon-paths.ts from Humbleicons (MIT, Jiří Zralý).
// Only the icons the app uses are copied, so the full set never ships to the browser.
// Run: npm run icons
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const set = JSON.parse(readFileSync(require.resolve("@iconify-json/humbleicons/icons.json"), "utf8"));

const used = ["dashboard", "pie-chart", "cloud-sun", "sparks", "package", "upload", "layers", "cog", "info-circle", "user", "bars", "times"];

const entries = used.map((name) => {
  const icon = set.icons[name];
  if (!icon) throw new Error(`Humbleicons has no "${name}"`);
  return `  ${JSON.stringify(name)}: ${JSON.stringify(icon.body)},`;
});

writeFileSync(
  new URL("../components/icons/icon-paths.ts", import.meta.url),
  `// Generated by scripts/generate-icons.mjs. Do not edit by hand.
// Humbleicons by Jiří Zralý, https://github.com/zraly/humbleicons
// MIT License; see components/icons/HUMBLEICONS-LICENSE.txt.

export const iconViewBox = "0 0 ${set.width ?? 24} ${set.height ?? 24}";

export const iconPaths = {
${entries.join("\n")}
} as const;

export type IconName = keyof typeof iconPaths;
`,
);
console.log(`Wrote ${used.length} icons.`);
